/* Experimental A2-Lite Cortex-M7 kernel. No device/firmware operations.
 * Architecture and weight order: NAM core, pinned in evidence/sources.json.
 * SPDX-License-Identifier: MIT
 * No heap, libc, transcendental functions or global mutable state.
 * Compile with FP contraction disabled for reproducible float32 comparisons.
 */
#include "geometry.h"

typedef struct {
    unsigned write[N_LAYERS + 1];
    float history[HISTORY_FLOATS];
} NamState;

/* w: rechannel[3], per layer {bias[3], mix[3], conv[t][in][out],
 * residual_bias[3], residual[in][out]}, head_bias, head[t][ch], scale.
 * Generated by model.py from the original NAM weights, never WAV-normalized.
 */
static void layer_constant(const float *w, const float x[3], float a[3],
                           unsigned k) {
    for (unsigned i = 0; i < 3; ++i) {
        float v = w[i] + w[3+i] * 0.0f;
        for (unsigned t = 0; t < k; ++t)
            for (unsigned j = 0; j < 3; ++j)
                v = v + w[6 + t*9 + j*3+i] * x[j];
        a[i] = v < 0.0f ? v * 0.01f : v;
    }
}

void nam_reset(NamState *s, const float *model) {
    float x[3] = {0,0,0}, hs[3] = {0,0,0}, a[3];
    for (unsigned l = 0; l < N_LAYERS; ++l) {
        s->write[l] = 0;
        float *r = s->history + ring_offset[l];
        for (unsigned p = 0; p < ring_length[l]; ++p)
            for (unsigned j = 0; j < 3; ++j) r[p*3+j] = x[j];
        const float *w = model + weight_offset[l];
        layer_constant(w, x, a, kernels[l]);
        const float *rw = w + 6 + 9*kernels[l];
        for (unsigned i = 0; i < 3; ++i) {
            hs[i] = hs[i] + a[i];
            float v = rw[i];
            for (unsigned j = 0; j < 3; ++j) v = v + rw[3+j*3+i]*a[j];
            x[i] = x[i] + v;
        }
    }
    s->write[N_LAYERS] = 0;
    for (unsigned t = 0; t < 16; ++t)
        for (unsigned j = 0; j < 3; ++j)
            s->history[HEAD_RING_OFFSET+t*3+j] = hs[j];
}

void nam_process(NamState *s, const float *model, const float *input,
                 float *output, unsigned count) {
    for (unsigned n = 0; n < count; ++n) {
        const float in = input[n];
        float x[3], hs[3] = {0,0,0}, a[3];
        for (unsigned j = 0; j < 3; ++j) x[j] = model[j]*in;
        for (unsigned l = 0; l < N_LAYERS; ++l) {
            const unsigned len = ring_length[l], k = kernels[l];
            const float *w = model + weight_offset[l];
            float *r = s->history + ring_offset[l];
            unsigned p = s->write[l];
            for (unsigned j = 0; j < 3; ++j) r[p*3+j] = x[j];
            if (++p == len) p = 0;
            s->write[l] = p; /* oldest tap; the last tap is current input */
            /* Gather each dilated input once for all three output channels.
             * Accumulation order within each channel stays tap -> input. */
            float v0 = w[0]+w[3]*in, v1 = w[1]+w[4]*in, v2 = w[2]+w[5]*in;
            unsigned tap = p;
            const float *cw = w+6;
            for (unsigned t = 0; t < k; ++t) {
                for (unsigned j = 0; j < 3; ++j) {
                    float value = r[tap*3+j];
                    v0 = v0 + cw[0]*value;
                    v1 = v1 + cw[1]*value;
                    v2 = v2 + cw[2]*value;
                    cw += 3;
                }
                tap += dilations[l];
                if (tap >= len) tap -= len;
            }
            a[0] = v0 < 0.0f ? v0*0.01f : v0;
            a[1] = v1 < 0.0f ? v1*0.01f : v1;
            a[2] = v2 < 0.0f ? v2*0.01f : v2;
            for (unsigned i = 0; i < 3; ++i) {
                hs[i] = hs[i] + a[i];
            }
            const float *rw = w + 6 + k*9;
            for (unsigned i = 0; i < 3; ++i) {
                float v = rw[i];
                for (unsigned j = 0; j < 3; ++j) v = v + rw[3+j*3+i]*a[j];
                x[i] = x[i] + v;
            }
        }
        float *hr = s->history + HEAD_RING_OFFSET;
        unsigned p = s->write[N_LAYERS];
        for (unsigned j = 0; j < 3; ++j) hr[p*3+j] = hs[j];
        if (++p == 16) p = 0;
        s->write[N_LAYERS] = p;
        const float *hw = model + HEAD_WEIGHT_OFFSET;
        float y = *hw++;
        for (unsigned t = 0; t < 16; ++t) {
            for (unsigned j = 0; j < 3; ++j) y = y + *hw++ * hr[p*3+j];
            if (++p == 16) p = 0;
        }
        output[n] = y*model[N_WEIGHTS-1];
    }
}

unsigned nam_state_bytes(void) { return sizeof(NamState); }

/* Experimental graph adapter. The caller must own and reserve all five
 * addresses; no loader or live-firmware hook is installed by this source. */
typedef struct {
    NamState *state;
    const float *model;
    const float *input;
    float *output;
    unsigned count;
} NamGraph;
void catalyst_nam_graph(NamGraph *g) {
    nam_process(g->state, g->model, g->input, g->output, g->count);
}

/* OFFLINE integration experiment: identify the stock Nuclear module by its
 * serialized definition signature, not by a volatile runtime graph pointer.
 * STATE/WEIGHTS below must be initialized by an explicitly extended boot table.
 * This function does not create that reservation or authorize a device flash.
 */
int catalyst_nam_try_route(const unsigned *arena, const unsigned *graph) {
    if (arena[0x14c/4] != 128) return 0;
    unsigned def_address=graph[0x14/4];
    if (def_address < 0x80000000u || def_address > 0x81ffffe0u) return 0;
    const unsigned *def=(const unsigned *)def_address;
    if (def[0]!=1 || def[1]!=4 || def[2]!=0x3a || def[3]!=0x2f828 ||
        def[4]!=4 || def[5]!=0x310c8) return 0;
    unsigned count=graph[3];
    if (count<2 || count>128) return 0;
    unsigned ptr=graph[2];
    if (ptr<0x20000000u || ptr>0x20068000u-count*20) return 0;
    const unsigned *entry=(const unsigned *)ptr;
    if(entry[0]!=1 || entry[1]!=1) return 0;
    unsigned source=entry[3], destination=0;
    for(unsigned i=0;i<count;++i)
        if(entry[i*5]==1 && entry[i*5+1]==1) destination=entry[i*5+4];
    /* Only the topology observed for this exact AmpSlot is admitted. */
    if(source!=0x20001270u || destination!=0x200012f0u) return 0;
    nam_process((NamState*)0x20050040u,(const float*)0x20062b40u,
                (const float*)source,(float*)destination,32);
    return 1;
}
