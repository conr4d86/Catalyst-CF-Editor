/* Experimental A2-Lite Cortex-M7 kernel. No device/firmware operations.
 * Architecture and weight order: NAM core, pinned in evidence/sources.json.
 * SPDX-License-Identifier: MIT
 * No heap, libc, transcendental functions or global mutable state.
 * Compile with FP contraction disabled for reproducible float32 comparisons.
 */
#include "geometry.h"

typedef struct {
    unsigned write[N_LAYERS + 1];
    float history[HISTORY_FLOATS];
} NamState;

/* w: rechannel[3], per layer {bias[3], mix[3], conv[t][in][out],
 * residual_bias[3], residual[in][out]}, head_bias, head[t][ch], scale.
 * Generated by model.py from the original NAM weights, never WAV-normalized.
 */

extern void nam_accumulate_span(float*,const float*,unsigned,const float*);
__asm__(
".syntax unified\n.text\n.thumb\n.thumb_func\n.global nam_accumulate_span\n"
".type nam_accumulate_span,%function\nnam_accumulate_span:\n"
"cmp r2,#0\nbeq 2f\nvldmia r3!,{s0-s8}\n1:\n"
"vldmia r1!,{s9-s11}\nvldmia r0,{s12-s14}\n"
"vfma.f32 s12,s0,s9\nvfma.f32 s13,s1,s9\nvfma.f32 s14,s2,s9\n"
"vfma.f32 s12,s3,s10\nvfma.f32 s13,s4,s10\nvfma.f32 s14,s5,s10\n"
"vfma.f32 s12,s6,s11\nvfma.f32 s13,s7,s11\nvfma.f32 s14,s8,s11\n"
"vstmia r0!,{s12-s14}\nsubs r2,r2,#1\nbne 1b\n2: bx lr\n"
".size nam_accumulate_span,.-nam_accumulate_span\n");

static __attribute__((always_inline)) inline float nam_leaky(float x){
    float product,result;
    __asm__("vmul.f32 %0,%2,%3\n\tvmaxnm.f32 %1,%2,%0"
        : "=&t"(product),"=&t"(result):"t"(x),"t"(.01f));
    return result;
}
/* Layer-major 32-sample kernel. Same tap/input accumulation order as scalar.
 * No extra persistent history: defer writing the ring until all taps consume
 * its previous contents. Current-block inputs come from the x tile instead.
 */
void nam_process(NamState *__restrict s, const float *__restrict model,
                 const float *input, float *output, unsigned count) {
    while(count) {
        unsigned block=count>32?32:count;
        float (*x)[3]=(float(*)[3])0x20065800u;
        float (*hs)[3]=(float(*)[3])0x20065980u;
        float (*a)[3]=(float(*)[3])0x20065b00u;
        for(unsigned n=0;n<block;++n)for(unsigned j=0;j<3;++j) {
            x[n][j]=model[j]*input[n];hs[n][j]=0;
        }
        for(unsigned l=0;l<N_LAYERS;++l) {
            const float *w=model+weight_offset[l];
            unsigned len=ring_length[l],k=kernels[l],d=dilations[l],start=s->write[l];
            float *history=s->history+ring_offset[l];
            for(unsigned n=0;n<block;++n) {
                a[n][0]=w[0]+w[3]*input[n];
                a[n][1]=w[1]+w[4]*input[n];
                a[n][2]=w[2]+w[5]*input[n];
            }
            for(unsigned t=0;t<k;++t){
                const float *cw=w+6+t*9;
                unsigned delay=(k-1-t)*d,old=delay<block?delay:block;
                unsigned pos=start>=delay?start-delay:start+len-delay;
                unsigned first=old<len-pos?old:len-pos;
                if(first)nam_accumulate_span(&a[0][0],history+pos*3,first,cw);
                if(old>first)nam_accumulate_span(&a[first][0],history,old-first,cw);
                if(block>old)nam_accumulate_span(&a[old][0],&x[old-delay][0],block-old,cw);
            }
            const float *rw=w+6+k*9;
            unsigned pos=start;
            for(unsigned n=0;n<block;++n) {
                for(unsigned j=0;j<3;++j)history[pos*3+j]=x[n][j];
                if(++pos==len)pos=0;
                float a0=a[n][0],a1=a[n][1],a2=a[n][2];
                a0=nam_leaky(a0);a1=nam_leaky(a1);a2=nam_leaky(a2);
                hs[n][0]+=a0;hs[n][1]+=a1;hs[n][2]+=a2;
                float v0=rw[0],v1=rw[1],v2=rw[2];
                v0+=rw[3]*a0;v1+=rw[4]*a0;v2+=rw[5]*a0;
                v0+=rw[6]*a1;v1+=rw[7]*a1;v2+=rw[8]*a1;
                v0+=rw[9]*a2;v1+=rw[10]*a2;v2+=rw[11]*a2;
                x[n][0]+=v0;x[n][1]+=v1;x[n][2]+=v2;
            }
            s->write[l]=pos;
        }
        float *hr=s->history+HEAD_RING_OFFSET;
        unsigned pos=s->write[N_LAYERS];
        const float *head=model+HEAD_WEIGHT_OFFSET;
        for(unsigned n=0;n<block;++n) {
            for(unsigned j=0;j<3;++j)hr[pos*3+j]=hs[n][j];
            if(++pos==16)pos=0;
            unsigned tap=pos;const float *w=head;
            float y=*w++;
            for(unsigned t=0;t<16;++t) {
                for(unsigned j=0;j<3;++j)y+=*w++*hr[tap*3+j];
                if(++tap==16)tap=0;
            }
            output[n]=y*model[N_WEIGHTS-1];
        }
        s->write[N_LAYERS]=pos;
        input+=block;output+=block;count-=block;
    }
}
unsigned nam_state_bytes(void) {return sizeof(NamState);}
